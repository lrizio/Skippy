'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('skippy', {
  loadSettings: () => ipcRenderer.invoke('settings:load'),
  saveSettings: patch => ipcRenderer.invoke('settings:save', patch),
  setAutostart: on => ipcRenderer.invoke('autostart:set', on),
  makeQr: text => ipcRenderer.invoke('qr:make', text),
  checkUpdate: wsUrl => ipcRenderer.invoke('update:check', wsUrl),
  openExternal: url => ipcRenderer.send('open:external', url),
  hideToTray: () => ipcRenderer.send('win:hide'),
  showWindow: () => ipcRenderer.send('win:show'),
  setFullscreen: on => ipcRenderer.send('win:fullscreen', !!on),
  screenSources: () => ipcRenderer.invoke('screen:sources'),
  screenPick: id => ipcRenderer.invoke('screen:pick', id),
  // received files are written to disk by the main process instead of piling up in memory
  fileOpen: id => ipcRenderer.invoke('file:open', id),
  fileWrite: (id, data) => ipcRenderer.send('file:write', id, data),
  fileClose: id => ipcRenderer.invoke('file:close', id),
  fileDiscard: id => ipcRenderer.invoke('file:discard', id),
  fileSave: (id, name) => ipcRenderer.invoke('file:save', id, name),
  // call recording + transcription (see recorder.js)
  recStart: room => ipcRenderer.invoke('rec:start', room),
  recOpen: (name, id, speaker, offsetMs) => ipcRenderer.invoke('rec:open', name, id, speaker, offsetMs),
  recWrite: (name, id, data) => ipcRenderer.send('rec:write', name, id, data),
  recClose: (name, id) => ipcRenderer.invoke('rec:close', name, id),
  recMeta: name => ipcRenderer.invoke('rec:meta', name),
  recFinish: name => ipcRenderer.invoke('rec:finish', name),
  recList: () => ipcRenderer.invoke('rec:list'),
  recTracks: name => ipcRenderer.invoke('rec:tracks', name),
  recReadTrack: (name, file) => ipcRenderer.invoke('rec:read-track', name, file),
  recOpenFolder: name => ipcRenderer.invoke('rec:open-folder', name),
  recOpenTranscript: name => ipcRenderer.invoke('rec:open-transcript', name),
  recSaveTranscript: (name, text) => ipcRenderer.invoke('rec:save-transcript', name, text),
  recEngineStatus: () => ipcRenderer.invoke('rec:engine-status'),
  recEngineInstall: () => ipcRenderer.invoke('rec:engine-install'),
  onRecProgress: cb => ipcRenderer.on('rec:progress', (_e, p) => cb(p)),
  recWavOpen: () => ipcRenderer.invoke('rec:wav-open'),
  recWavWrite: (id, data) => ipcRenderer.send('rec:wav-write', id, data),
  recWavTranscribe: id => ipcRenderer.invoke('rec:wav-transcribe', id),
});
